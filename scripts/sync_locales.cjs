function getValueByKey(obj, keyPath) {
  return keyPath.split('.').reduce((prev, curr) => prev && prev[curr], obj);
}

function setValueByKey(obj, keyPath, value) {
  const parts = keyPath.split('.');
  const last = parts.pop();
  let current = obj;
  for (const part of parts) {
    if (!current[part]) current[part] = {};
    current = current[part];
  }
  current[last] = value;
}

function sync(target, source, lang, currentPath = '') {
  for (const key in source) {
    const fullPath = currentPath ? `${currentPath}.${key}` : key;
    if (typeof source[key] === 'object' && !Array.isArray(source[key])) {
      if (!target[key] || typeof target[key] !== 'object') target[key] = {};
      sync(target[key], source[key], lang, fullPath);
    } else {
      if (target[key] === undefined) {
        // Try to get from translation map
        const translated = translations[lang] && translations[lang][fullPath];
        target[key] = translated || source[key];
        console.log(`[${lang}] Added: ${fullPath} -> ${target[key]}`);
      }
    }
  }
}

